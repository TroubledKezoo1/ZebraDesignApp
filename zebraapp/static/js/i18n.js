  function detect() {
    var v = null;
    try { v = localStorage.getItem(KEY); } catch (e) { v = null; }
    if (v === "tr" || v === "en" || v === "pt") return v;
    var n = (navigator.language || "tr").toLowerCase();
    if (n.indexOf("tr") === 0) return "tr";
    if (n.indexOf("pt") === 0) return "pt";
    return "en";
  }
  var lang = detect();

  function dictFor(l) {
    if (l === "en") return EN;
    if (l === "pt") return PT;
    return null;
  }

  function t(s) {
    var d = dictFor(lang);
    if (!d || s == null) return s;
    return Object.prototype.hasOwnProperty.call(d, s) ? d[s] : s;
  }

  function apply(root) {
    if (lang === "tr") return;
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        var p = n.parentNode;
        if (!p || /^(SCRIPT|STYLE|TEXTAREA)$/.test(p.nodeName) || p.closest("svg")) return NodeFilter.FILTER_REJECT;
        return n.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    var nodes = [], n;
    while ((n = walker.nextNode())) nodes.push(n);
    nodes.forEach(function (node) {
      var raw = node.nodeValue, key = raw.trim(), tr = t(key);
      if (tr !== key) node.nodeValue = raw.replace(key, tr);
    });
    /* data-token da çevrilir: böylece PT-BR kullanıcıları gerçekten {DATA+N} ekler.
       i18n.js editor.js'ten önce yüklendiği için, editor.js bu değeri okuduğunda
       jeton çoktan {DATA+N} olur. */
    ["title", "placeholder", "alt", "aria-label", "data-token"].forEach(function (a) {
      Array.prototype.forEach.call(root.querySelectorAll("[" + a + "]"), function (el) {
        var v = el.getAttribute(a), tr = t(v);
        if (tr !== v) el.setAttribute(a, tr);
      });
    });
  }

  function setLang(v) {
    v = (v === "en" || v === "pt") ? v : "tr";
    try { localStorage.setItem(KEY, v); } catch (e) { /* yok sayilir */ }
    if (v !== lang) { location.reload(); return true; }
    return false;
  }

  document.documentElement.lang = lang;
  window.I18N = { t: t, apply: apply, setLang: setLang, get lang() { return lang; }, EN: EN, PT: PT };
